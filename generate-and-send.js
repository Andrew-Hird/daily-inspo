const RESEND_API_KEY = process.env.RESEND_API_KEY;
const RECIPIENT_EMAIL = process.env.RECIPIENT_EMAIL;
const SENDER_EMAIL = process.env.SENDER_EMAIL;

if (!RESEND_API_KEY || !RECIPIENT_EMAIL || !SENDER_EMAIL) {
	console.error(
		"Missing required environment variables: RESEND_API_KEY, RECIPIENT_EMAIL, SENDER_EMAIL",
	);
	process.exit(1);
}

const PROMPT = "A Minion in a random funny or dramatic pose, vibrant cartoon style, different colorful setting each day — could be an office, beach, space, jungle, kitchen, or anywhere unexpected, bright cheerful lighting, inspirational poster aesthetic, wide aspect ratio";

async function generateImage() {
	const url = `https://image.pollinations.ai/prompt/${encodeURIComponent(PROMPT)}`;
	const response = await fetch(url);

	if (!response.ok) {
		throw new Error(`Pollinations error ${response.status}`);
	}

	const buffer = await response.arrayBuffer();
	const base64 = Buffer.from(buffer).toString('base64');
	const mimeType = response.headers.get('content-type') || 'image/jpeg';

	return { base64, mimeType };
}

async function sendEmail(mimeType, base64Image) {
	const html = `
    <div style="font-family: sans-serif; max-width: 700px; margin: 0 auto;">
      <h2 style="color: #333;">Your daily inspo</h2>
      <img src="data:${mimeType};base64,${base64Image}" alt="Daily minion" style="width: 100%; border-radius: 8px;" />
      <p style="color: #888; font-size: 12px; margin-top: 12px;">Generated by Pollinations · Sent via daily-inspo</p>
    </div>
  `;

	const response = await fetch("https://api.resend.com/emails", {
		method: "POST",
		headers: {
			"Content-Type": "application/json",
			Authorization: `Bearer ${RESEND_API_KEY}`,
		},
		body: JSON.stringify({
			from: SENDER_EMAIL,
			to: RECIPIENT_EMAIL.split(',').map((e) => e.trim()),
			subject: `Daily inspo — ${new Date().toLocaleDateString("en-US", { weekday: "long", month: "long", day: "numeric" })}`,
			html,
		}),
	});

	if (!response.ok) {
		const body = await response.text();
		throw new Error(`Resend API error ${response.status}: ${body}`);
	}

	return await response.json();
}

try {
	console.log("Generating image with Pollinations...");
	const { base64, mimeType } = await generateImage();
	console.log(`Image received (${mimeType})`);

	console.log("Sending email via Resend...");
	const result = await sendEmail(mimeType, base64);
	console.log(`Email sent successfully (id: ${result.id})`);
} catch (err) {
	console.error("Error:", err.message);
	process.exit(1);
}
