const GEMINI_API_KEY = process.env.GEMINI_API_KEY;
const RESEND_API_KEY = process.env.RESEND_API_KEY;
const RECIPIENT_EMAIL = process.env.RECIPIENT_EMAIL;
const SENDER_EMAIL = process.env.SENDER_EMAIL;

if (!GEMINI_API_KEY || !RESEND_API_KEY || !RECIPIENT_EMAIL || !SENDER_EMAIL) {
	console.error(
		"Missing required environment variables: GEMINI_API_KEY, RESEND_API_KEY, RECIPIENT_EMAIL, SENDER_EMAIL",
	);
	process.exit(1);
}

async function generateImage() {
	const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-3.1-flash-image-preview:generateContent?key=${GEMINI_API_KEY}`;

	const response = await fetch(url, {
		method: "POST",
		headers: { "Content-Type": "application/json" },
		body: JSON.stringify({
			contents: [
				{
					parts: [
						{
							text: "A Minion in a random funny or dramatic pose, vibrant cartoon style, different colorful setting each day — could be an office, beach, space, jungle, kitchen, or anywhere unexpected, bright cheerful lighting, inspirational poster aesthetic, wide aspect ratio",
						},
					],
				},
			],
			generationConfig: { responseModalities: ["IMAGE", "TEXT"] },
		}),
	});

	if (!response.ok) {
		const body = await response.text();
		throw new Error(`Gemini API error ${response.status}: ${body}`);
	}

	const data = await response.json();
	const parts = data.candidates?.[0]?.content?.parts ?? [];
	const imagePart = parts.find((p) => p.inlineData);

	if (!imagePart) {
		throw new Error("No image data in Gemini response");
	}

	return imagePart.inlineData;
}

async function sendEmail(mimeType, base64Image) {
	const html = `
    <div style="font-family: sans-serif; max-width: 700px; margin: 0 auto;">
      <h2 style="color: #333;">Your daily landscape</h2>
      <img src="data:${mimeType};base64,${base64Image}" alt="AI-generated landscape" style="width: 100%; border-radius: 8px;" />
      <p style="color: #888; font-size: 12px; margin-top: 12px;">Generated by Gemini · Sent via daily-inspo</p>
    </div>
  `;

	const response = await fetch("https://api.resend.com/emails", {
		method: "POST",
		headers: {
			"Content-Type": "application/json",
			Authorization: `Bearer ${RESEND_API_KEY}`,
		},
		body: JSON.stringify({
			from: SENDER_EMAIL,
			to: RECIPIENT_EMAIL.split(',').map((e) => e.trim()),
			subject: `Daily inspo — ${new Date().toLocaleDateString("en-US", { weekday: "long", month: "long", day: "numeric" })}`,
			html,
		}),
	});

	if (!response.ok) {
		const body = await response.text();
		throw new Error(`Resend API error ${response.status}: ${body}`);
	}

	return await response.json();
}

try {
	console.log("Generating image with Gemini...");
	const { mimeType, data: base64Image } = await generateImage();
	console.log(`Image received (${mimeType})`);

	console.log("Sending email via Resend...");
	const result = await sendEmail(mimeType, base64Image);
	console.log(`Email sent successfully (id: ${result.id})`);
} catch (err) {
	console.error("Error:", err.message);
	process.exit(1);
}
